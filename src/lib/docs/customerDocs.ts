/**
 * Generates a unified Markdown bundle of all customer documents for bulk download.
 */
export function generateDocumentationBundle(): string {
  const date = new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  let bundle = `# ShieldDesk™ Customer Documentation & Enterprise Manual
**Compiled On:** ${date}  
**Publisher:** Mints Global Security Engineering  
**Classification:** Customer-Facing Enterprise Guide  

---

## Table of Contents
`;

  CUSTOMER_DOCUMENTS.forEach((doc, idx) => {
    bundle += `${idx + 1}. [${doc.title}](#${doc.id}) - *${doc.category}*\n`;
  });

  bundle += `\n---\n\n`;

  CUSTOMER_DOCUMENTS.forEach((doc) => {
    bundle += `<a name="${doc.id}"></a>\n\n`;
    bundle += `## ${doc.title}\n`;
    bundle += `**Category:** ${doc.category} | **Estimated Read Time:** ${doc.readTime} | **Last Updated:** ${doc.lastUpdated}\n\n`;
    bundle += `${doc.content}\n\n`;
    bundle += `---\n\n`;
  });

  bundle += `\n*End of ShieldDesk Customer Documentation Manual. © ${new Date().getFullYear()} Mints Global Security Engineering. All Rights Reserved.*`;

  return bundle;
}
